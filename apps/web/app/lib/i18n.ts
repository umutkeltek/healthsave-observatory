const DEFAULT_LOCALE: Locale = "en";
const RELEASED_LOCALES: readonly Locale[] = [DEFAULT_LOCALE];

export function parseLocale(raw: string | undefined | null): Locale {
  return LOCALES.includes(raw as Locale) ? (raw as Locale) : DEFAULT_LOCALE;
}

export function availableLocales(includePreview: boolean): readonly Locale[] {
  return includePreview ? LOCALES : RELEASED_LOCALES;
}

export function resolveAvailableLocale(
  raw: string | undefined | null,
  includePreview: boolean,
): Locale {
  const parsed = parseLocale(raw);
  return availableLocales(includePreview).includes(parsed) ? parsed : DEFAULT_LOCALE;
}

